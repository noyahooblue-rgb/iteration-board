-- M4：AI 服务层 / 导入批次 / 外部对接 / 审计日志（Q1）/ 报告迭代唯一（Q7）

-- 1) 审计日志（Q1/Q6：本轮只建表与写入点，读取界面放 M5）
CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id     BIGINT REFERENCES team(id),
    actor_id    BIGINT NOT NULL REFERENCES app_user(id),
    action      VARCHAR(64) NOT NULL,
    target_type VARCHAR(32) NOT NULL,
    target_id   BIGINT,
    detail      TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_team_created ON audit_log(team_id, created_at DESC);

-- 2) 小组 AI 逐项开关（平台总开关在配置文件 ai.platform-enabled）
CREATE TABLE team_ai_settings (
    team_id             BIGINT PRIMARY KEY REFERENCES team(id),
    paste_import        BOOLEAN NOT NULL DEFAULT TRUE,
    quick_update        BOOLEAN NOT NULL DEFAULT TRUE,
    split_stories       BOOLEAN NOT NULL DEFAULT TRUE,
    summarize           BOOLEAN NOT NULL DEFAULT TRUE,
    risk_summary        BOOLEAN NOT NULL DEFAULT TRUE,
    qa                  BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 3) AI 调用日志（设计 §7.1：功能/模型/耗时/用量/结果）
CREATE TABLE ai_call_log (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id          BIGINT REFERENCES team(id),
    user_id          BIGINT REFERENCES app_user(id),
    feature          VARCHAR(32) NOT NULL,
    model            VARCHAR(128),
    duration_ms      BIGINT NOT NULL DEFAULT 0,
    prompt_tokens    INT,
    completion_tokens INT,
    success          BOOLEAN NOT NULL DEFAULT FALSE,
    error            VARCHAR(500),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_ai_call_team_created ON ai_call_log(team_id, created_at DESC);

-- 4) AI 问答记录（§16.2：仅本人可见、可删）
CREATE TABLE ai_qa_record (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id    BIGINT NOT NULL REFERENCES team(id),
    user_id    BIGINT NOT NULL REFERENCES app_user(id),
    question   TEXT NOT NULL,
    answer     TEXT NOT NULL DEFAULT '',
    found      BOOLEAN NOT NULL DEFAULT FALSE,
    refs_json  TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_ai_qa_user ON ai_qa_record(team_id, user_id, created_at DESC);

-- 5) 导入批次（修订二 §16.2：发起人/组长 24 小时内整批撤销；外部编号去重）
CREATE TABLE import_batch (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id       BIGINT NOT NULL REFERENCES team(id),
    creator_id    BIGINT NOT NULL REFERENCES app_user(id),
    source        VARCHAR(32) NOT NULL,
    total         INT NOT NULL DEFAULT 0,
    created_count INT NOT NULL DEFAULT 0,
    updated_count INT NOT NULL DEFAULT 0,
    undone_at     TIMESTAMPTZ,
    undone_by     BIGINT REFERENCES app_user(id),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_import_batch_team ON import_batch(team_id, created_at DESC);

CREATE TABLE import_batch_item (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        BIGINT NOT NULL REFERENCES import_batch(id),
    item_id         BIGINT NOT NULL REFERENCES item(id),
    action          VARCHAR(16) NOT NULL,
    prev_title      VARCHAR(200),
    prev_description TEXT,
    prev_due_date   DATE
);
CREATE INDEX idx_import_batch_item_batch ON import_batch_item(batch_id);

-- 6) 对接适配器与同步日志（设计 §9）
CREATE TABLE integration_adapter (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id              BIGINT NOT NULL REFERENCES team(id),
    name                 VARCHAR(100) NOT NULL,
    type                 VARCHAR(16) NOT NULL,
    system_name          VARCHAR(64) NOT NULL,
    config_json          TEXT NOT NULL DEFAULT '{}',
    enabled              BOOLEAN NOT NULL DEFAULT TRUE,
    consecutive_failures INT NOT NULL DEFAULT 0,
    created_by           BIGINT NOT NULL REFERENCES app_user(id),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_adapter_team ON integration_adapter(team_id);

CREATE TABLE sync_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    adapter_id    BIGINT NOT NULL REFERENCES integration_adapter(id),
    team_id       BIGINT NOT NULL REFERENCES team(id),
    actor_id      BIGINT REFERENCES app_user(id),
    created_count INT NOT NULL DEFAULT 0,
    updated_count INT NOT NULL DEFAULT 0,
    failed_count  INT NOT NULL DEFAULT 0,
    message       VARCHAR(1000),
    success       BOOLEAN NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_sync_log_adapter ON sync_log(adapter_id, created_at DESC);

-- 7) 事项：外部已关闭标记（设计 §9 同步规则）+ 删除人（Q9 统一回收站）
ALTER TABLE item ADD COLUMN external_closed BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE item ADD COLUMN deleted_by_id BIGINT REFERENCES app_user(id);
ALTER TABLE report ADD COLUMN deleted_by_id BIGINT REFERENCES app_user(id);

-- 8) Q7：迭代总结按 iterationId 唯一（一迭代一份，含墓碑行）
CREATE UNIQUE INDEX uq_report_iteration_summary
    ON report(team_id, iteration_id)
    WHERE kind = 'ITERATION_SUMMARY' AND iteration_id IS NOT NULL;
