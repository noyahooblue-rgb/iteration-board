-- M3（协同）：通知带小组、迭代关闭时间、燃尽快照、关键日期、站会备注、报告。
-- 通知偏好复用 app_user.preferences_json（JSON 内 notificationPrefs 键），不新增列。

-- 1) 通知补小组维度（通知中心按组过滤；回填自关联事项）
ALTER TABLE notification ADD COLUMN team_id BIGINT REFERENCES team(id);
UPDATE notification n SET team_id = i.team_id FROM item i WHERE n.item_id = i.id AND n.team_id IS NULL;
CREATE INDEX idx_notification_recipient_team ON notification(recipient_id, team_id, created_at DESC);
CREATE INDEX idx_notification_recipient_read ON notification(recipient_id, read_at);

-- 2) 迭代关闭时间
ALTER TABLE iteration ADD COLUMN closed_at TIMESTAMPTZ;

-- 3) 燃尽快照（设计 §5.3 iteration_snapshot，每晚 23:30 + 开始/结束/手动触发）
CREATE TABLE iteration_snapshot (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iteration_id      BIGINT NOT NULL REFERENCES iteration(id),
    snapshot_date     DATE NOT NULL,
    remaining_estimate NUMERIC(12,2) NOT NULL DEFAULT 0,
    remaining_count   INT NOT NULL DEFAULT 0,
    done_count        INT NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (iteration_id, snapshot_date)
);
CREATE INDEX idx_snapshot_iteration ON iteration_snapshot(iteration_id, snapshot_date);

-- 4) 关键日期（设计 §5.3 key_date）
CREATE TABLE key_date (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iteration_id BIGINT NOT NULL REFERENCES iteration(id),
    title        VARCHAR(200) NOT NULL,
    key_date     DATE NOT NULL,
    category     VARCHAR(16) NOT NULL DEFAULT 'OTHER',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_key_date_iteration ON key_date(iteration_id, key_date);

-- 5) 站会备注（设计 §5.3 standup_note，一组一天一条）
CREATE TABLE standup_note (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id    BIGINT NOT NULL REFERENCES team(id),
    note_date  DATE NOT NULL,
    content    TEXT NOT NULL DEFAULT '',
    updated_by BIGINT REFERENCES app_user(id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (team_id, note_date)
);

-- 6) 报告（设计 §5.3 report）
CREATE TABLE report (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id      BIGINT NOT NULL REFERENCES team(id),
    kind         VARCHAR(32) NOT NULL,
    title        VARCHAR(200) NOT NULL,
    period_start DATE,
    period_end   DATE,
    owner_id     BIGINT REFERENCES app_user(id),
    content      TEXT NOT NULL DEFAULT '',
    ai_generated BOOLEAN NOT NULL DEFAULT FALSE,
    edited       BOOLEAN NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_report_team_created ON report(team_id, created_at DESC);
