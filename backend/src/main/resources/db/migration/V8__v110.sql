CREATE TABLE feedback (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submitter_id     BIGINT NOT NULL REFERENCES app_user(id),
    type             VARCHAR(16) NOT NULL,
    title            VARCHAR(200) NOT NULL,
    description      TEXT NOT NULL,
    page_url         VARCHAR(500),
    app_version      VARCHAR(32),
    browser_info     VARCHAR(500),
    status           VARCHAR(16) NOT NULL DEFAULT 'NEW',
    planned_version  VARCHAR(32),
    reject_reason    VARCHAR(500),
    released_version VARCHAR(32),
    official_reply   TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_feedback_submitter_created ON feedback(submitter_id, created_at);
CREATE INDEX idx_feedback_status ON feedback(status);

CREATE TABLE feedback_plus_one (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_id BIGINT NOT NULL REFERENCES feedback(id),
    user_id     BIGINT NOT NULL REFERENCES app_user(id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_feedback_plus_one UNIQUE (feedback_id, user_id)
);

CREATE TABLE feedback_comment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_id BIGINT NOT NULL REFERENCES feedback(id),
    author_id   BIGINT NOT NULL REFERENCES app_user(id),
    content     TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_feedback_comment_feedback ON feedback_comment(feedback_id, created_at);

CREATE TABLE feedback_image (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_id   BIGINT NOT NULL REFERENCES feedback(id),
    file_name     VARCHAR(200) NOT NULL,
    content_type  VARCHAR(100) NOT NULL,
    size_bytes    BIGINT NOT NULL,
    content_base64 TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_feedback_image_feedback ON feedback_image(feedback_id);
