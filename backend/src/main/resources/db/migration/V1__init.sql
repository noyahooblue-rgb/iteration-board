-- M1 基础表结构（设计 §5）。时间统一 UTC 存储（timestamptz）；软删除字段 deleted_at 按 §5.5 预留。
CREATE TABLE app_user (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_name          VARCHAR(32)  NOT NULL UNIQUE,
    display_name        VARCHAR(64)  NOT NULL,
    password_hash       VARCHAR(100) NOT NULL,
    avatar_color        VARCHAR(16),
    platform_admin      BOOLEAN NOT NULL DEFAULT FALSE,
    status              VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    failed_attempts     INT NOT NULL DEFAULT 0,
    locked_until        TIMESTAMPTZ,
    password_version    INT NOT NULL DEFAULT 0,
    preferences_json    TEXT,
    deleted_at          TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE team (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(64) NOT NULL,
    code            VARCHAR(5)  NOT NULL,
    description     VARCHAR(500),
    invite_code     VARCHAR(16) NOT NULL UNIQUE,
    join_approval   BOOLEAN NOT NULL DEFAULT TRUE,
    iteration_weeks INT NOT NULL DEFAULT 2,
    estimate_unit   VARCHAR(8) NOT NULL DEFAULT 'day',
    theme_color     VARCHAR(16) NOT NULL DEFAULT 'blue',
    settings_json   TEXT,
    status          VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    item_seq        BIGINT NOT NULL DEFAULT 0,
    deleted_at      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE team_member (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id       BIGINT NOT NULL REFERENCES team(id),
    user_id       BIGINT NOT NULL REFERENCES app_user(id),
    role          VARCHAR(16) NOT NULL,
    member_status VARCHAR(16) NOT NULL DEFAULT 'NORMAL',
    status_start  DATE,
    status_end    DATE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (team_id, user_id)
);

CREATE TABLE join_request (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id     BIGINT NOT NULL REFERENCES team(id),
    user_id     BIGINT NOT NULL REFERENCES app_user(id),
    status      VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    approver_id BIGINT REFERENCES app_user(id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_at  TIMESTAMPTZ
);
CREATE INDEX idx_join_request_team_status ON join_request(team_id, status);

CREATE TABLE iteration (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id    BIGINT NOT NULL REFERENCES team(id),
    name       VARCHAR(100) NOT NULL,
    goal       TEXT,
    start_date DATE,
    end_date   DATE,
    status     VARCHAR(16) NOT NULL DEFAULT 'PLANNING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_iteration_team_status ON iteration(team_id, status);

CREATE TABLE item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id          BIGINT NOT NULL REFERENCES team(id),
    seq              BIGINT NOT NULL,
    code             VARCHAR(32) NOT NULL,
    type             VARCHAR(16) NOT NULL,
    title            VARCHAR(200) NOT NULL,
    description      TEXT,
    status           VARCHAR(16) NOT NULL,
    priority         VARCHAR(4) NOT NULL DEFAULT 'P2',
    creator_id       BIGINT NOT NULL REFERENCES app_user(id),
    assignee_id      BIGINT REFERENCES app_user(id),
    acceptor_id      BIGINT REFERENCES app_user(id),
    parent_id        BIGINT REFERENCES item(id),
    iteration_id     BIGINT REFERENCES iteration(id),
    backlog_order    BIGINT,
    due_date         DATE,
    estimate         NUMERIC(10,2),
    progress_percent INT NOT NULL DEFAULT 0,
    blocked          BOOLEAN NOT NULL DEFAULT FALSE,
    block_reason     VARCHAR(500),
    blocked_at       TIMESTAMPTZ,
    status_changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_progress_at TIMESTAMPTZ,
    nudge_count      INT NOT NULL DEFAULT 0,
    source           VARCHAR(16) NOT NULL DEFAULT 'MANUAL',
    external_system  VARCHAR(64),
    external_id      VARCHAR(64),
    external_url     VARCHAR(500),
    import_batch_id  BIGINT,
    archived_at      TIMESTAMPTZ,
    deleted_at       TIMESTAMPTZ,
    version          INT NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (team_id, seq)
);
CREATE INDEX idx_item_team_status ON item(team_id, status);
CREATE INDEX idx_item_team_assignee ON item(team_id, assignee_id);

CREATE TABLE item_collaborator (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES item(id),
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    UNIQUE (item_id, user_id)
);
CREATE TABLE item_invitee (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES item(id),
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    UNIQUE (item_id, user_id)
);
CREATE TABLE item_watcher (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES item(id),
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    UNIQUE (item_id, user_id)
);

CREATE TABLE label (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES team(id),
    name    VARCHAR(32) NOT NULL,
    color   VARCHAR(16),
    UNIQUE (team_id, name)
);
CREATE TABLE item_label (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id  BIGINT NOT NULL REFERENCES item(id),
    label_id BIGINT NOT NULL REFERENCES label(id),
    UNIQUE (item_id, label_id)
);

CREATE TABLE checklist_entry (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id    BIGINT NOT NULL REFERENCES item(id),
    text       VARCHAR(500) NOT NULL,
    done       BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INT NOT NULL DEFAULT 0
);

CREATE TABLE progress_update (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id      BIGINT NOT NULL REFERENCES item(id),
    author_id    BIGINT NOT NULL REFERENCES app_user(id),
    text         TEXT NOT NULL,
    percent      INT,
    blocked      BOOLEAN NOT NULL DEFAULT FALSE,
    block_reason VARCHAR(500),
    next_step    VARCHAR(500),
    kind         VARCHAR(16) NOT NULL DEFAULT 'NORMAL',
    channel      VARCHAR(16) NOT NULL DEFAULT 'MANUAL',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_progress_item ON progress_update(item_id, created_at);

CREATE TABLE comment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id    BIGINT NOT NULL REFERENCES item(id),
    author_id  BIGINT NOT NULL REFERENCES app_user(id),
    content    TEXT NOT NULL,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE comment_mention (
    comment_id BIGINT NOT NULL REFERENCES comment(id),
    user_id    BIGINT NOT NULL,
    PRIMARY KEY (comment_id, user_id)
);

CREATE TABLE activity (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id     BIGINT NOT NULL REFERENCES item(id),
    actor_id    BIGINT NOT NULL REFERENCES app_user(id),
    action      VARCHAR(32) NOT NULL,
    from_status VARCHAR(16),
    to_status   VARCHAR(16),
    detail      TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_activity_item ON activity(item_id, created_at);

-- 通知表先建（设计 §5.3），通知逻辑 M3 实现
CREATE TABLE notification (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES app_user(id),
    type         VARCHAR(32) NOT NULL,
    item_id      BIGINT REFERENCES item(id),
    actor_id     BIGINT REFERENCES app_user(id),
    content      VARCHAR(500),
    read_at      TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_notification_recipient ON notification(recipient_id, read_at);
