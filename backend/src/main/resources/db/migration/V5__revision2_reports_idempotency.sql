-- 修订二（§16.1 报告 / §16.2 权限 / §16.3 幂等）

-- 1) 报告：软删除（墓碑）、最近生成时间、人工编辑标记、乐观锁版本、所属迭代（迭代总结唯一性）
ALTER TABLE report ADD COLUMN deleted_at TIMESTAMPTZ;
ALTER TABLE report ADD COLUMN last_generated_at TIMESTAMPTZ;
ALTER TABLE report ADD COLUMN edited_by_human BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE report ADD COLUMN version INT NOT NULL DEFAULT 0;
ALTER TABLE report ADD COLUMN iteration_id BIGINT REFERENCES iteration(id);
UPDATE report SET edited_by_human = edited, last_generated_at = created_at;
CREATE INDEX idx_report_team_kind_period ON report(team_id, kind, period_start, period_end);
CREATE INDEX idx_report_iteration ON report(iteration_id);

-- 2) 报告历史版本（每份最多 5 个，应用层裁剪最旧）
CREATE TABLE report_version (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id       BIGINT NOT NULL REFERENCES report(id),
    title           VARCHAR(200) NOT NULL,
    content         TEXT NOT NULL DEFAULT '',
    edited_by_human BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_report_version_report ON report_version(report_id, created_at DESC, id DESC);

-- 3) 幂等记录（§16.3：同用户 + 同端点范围 + 同键，10 分钟内只生效一次）
CREATE TABLE idempotency_record (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES app_user(id),
    scope           VARCHAR(200) NOT NULL,
    idem_key        VARCHAR(128) NOT NULL,
    response_status INT NOT NULL,
    response_body   TEXT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, scope, idem_key)
);
CREATE INDEX idx_idempotency_created ON idempotency_record(created_at);

-- 4) 评论补 updated_at（修订二 §16.2：作者 15 分钟内可改）
ALTER TABLE comment ADD COLUMN updated_at TIMESTAMPTZ;
UPDATE comment SET updated_at = created_at;
