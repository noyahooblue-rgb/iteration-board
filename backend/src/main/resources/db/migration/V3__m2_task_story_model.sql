-- M2（修订一）：任务/故事模型、共同负责、批量下发。
-- 1) 类型值迁移（顺序关键）：先把 REQUIREMENT 暂存，再 TASK→STORY，最后暂存→TASK。
UPDATE item SET type = '__REQ__' WHERE type = 'REQUIREMENT';
UPDATE item SET type = 'STORY' WHERE type = 'TASK';
UPDATE item SET type = 'TASK' WHERE type = '__REQ__';

-- 2) 事项新列：故事类别、所属 PO、批次、是否直接指派、任务内排序。
ALTER TABLE item ADD COLUMN story_category VARCHAR(16);
ALTER TABLE item ADD COLUMN po_id BIGINT REFERENCES app_user(id);
ALTER TABLE item ADD COLUMN batch_id BIGINT;
ALTER TABLE item ADD COLUMN assigned_directly BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE item ADD COLUMN sort_order INT NOT NULL DEFAULT 0;
-- 存量任务（原需求）的所属 PO 回填为创建人
UPDATE item SET po_id = creator_id WHERE type = 'TASK' AND po_id IS NULL;

-- 3) 负责人一对多（共同负责）：回填自 assignee_id 后删除旧列。
CREATE TABLE item_owner (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES item(id),
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    UNIQUE (item_id, user_id)
);
CREATE INDEX idx_item_owner_user ON item_owner(user_id);
INSERT INTO item_owner (item_id, user_id)
SELECT id, assignee_id FROM item WHERE assignee_id IS NOT NULL;
ALTER TABLE item DROP COLUMN assignee_id;

-- 4) 下发批次表（修订一第 7 节）。
CREATE TABLE dispatch_batch (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id    BIGINT NOT NULL REFERENCES team(id),
    creator_id BIGINT NOT NULL REFERENCES app_user(id),
    title      VARCHAR(200) NOT NULL,
    item_type  VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE item ADD CONSTRAINT fk_item_batch FOREIGN KEY (batch_id) REFERENCES dispatch_batch(id);
CREATE INDEX idx_item_batch ON item(batch_id);

-- 5) 催更记录表：同一人对同一事项每天一次的判定依据。
CREATE TABLE nudge (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id    BIGINT NOT NULL REFERENCES item(id),
    nudger_id  BIGINT NOT NULL REFERENCES app_user(id),
    target_id  BIGINT NOT NULL REFERENCES app_user(id),
    response   VARCHAR(16),
    responded_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_nudge_item_created ON nudge(item_id, created_at);

-- 6) 保存筛选。
CREATE TABLE saved_filter (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id       BIGINT NOT NULL REFERENCES team(id),
    user_id       BIGINT NOT NULL REFERENCES app_user(id),
    name          VARCHAR(64) NOT NULL,
    criteria_json TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_saved_filter_user ON saved_filter(team_id, user_id);

-- 7) 估算单位：新建小组默认改为故事点（POINTS 语义，存量值 day/point 不变；仅改列默认值）。
ALTER TABLE team ALTER COLUMN estimate_unit SET DEFAULT 'point';
