package com.iterationboard.reminder;

import com.iterationboard.domain.Iteration;
import com.iterationboard.iteration.IterationService;
import com.iterationboard.repo.IterationRepo;
import com.iterationboard.report.ReportService;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDate;

/**
 * 定时任务：工作日 9–18 点每小时自动提醒扫描；每晚 23:30 燃尽快照；
 * 每日凌晨（默认 3:17，cron 可配 app.retention.purge-cron）留存物理清理（M5，Q4）。
 */
@Component
public class ScheduledJobs {
    private static final Logger log = LoggerFactory.getLogger(ScheduledJobs.class);
    private final ReminderService reminderService;
    private final IterationRepo iterationRepo;
    private final IterationService iterationService;
    private final ReportService reportService;
    private final com.iterationboard.retention.RetentionPurgeService retentionPurgeService;

    public ScheduledJobs(ReminderService reminderService, IterationRepo iterationRepo, IterationService iterationService,
                         ReportService reportService,
                         com.iterationboard.retention.RetentionPurgeService retentionPurgeService) {
        this.reminderService = reminderService;
        this.iterationRepo = iterationRepo;
        this.iterationService = iterationService;
        this.reportService = reportService;
        this.retentionPurgeService = retentionPurgeService;
    }

    /** M5（Q4）：回收站 30 天 / 通知 90 天 / 审计日志 180 天物理清理（保留期见 app.retention.*）。 */
    @Scheduled(cron = "${app.retention.purge-cron:0 17 3 * * *}")
    public void retentionPurge() {
        retentionPurgeService.purge();
    }

    /** ：工作日 9:00 自动生成当日站会摘要 + 风险摘要（已存在/墓碑则跳过）。 */
    @Scheduled(cron = "0 0 9 * * MON-FRI")
    public void dailyReports() {
        int created = reportService.autoGenerateDaily(LocalDate.now());
        if (created > 0) log.info("站会/风险摘要自动生成 {} 份", created);
    }

    /** ：周五 16:00 自动生成当周周报（已存在/墓碑则跳过）。 */
    @Scheduled(cron = "0 0 16 * * FRI")
    public void weeklyReport() {
        int created = reportService.autoGenerateWeekly(LocalDate.now());
        if (created > 0) log.info("周报自动生成 {} 份", created);
    }

    @Scheduled(cron = "0 5 9-18 * * MON-FRI")
    public void hourlyReminderScan() {
        int created = reminderService.scanAll();
        if (created > 0) log.info("自动提醒扫描完成，新生成 {} 条", created);
    }

    @Scheduled(cron = "0 30 23 * * *")
    @Transactional
    public void nightlySnapshots() {
        LocalDate today = LocalDate.now();
        for (Iteration it : iterationRepo.findByStatus("ACTIVE")) {
            iterationService.takeSnapshot(it, today);
        }
    }
}
